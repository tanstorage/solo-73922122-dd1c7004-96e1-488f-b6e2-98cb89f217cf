"""Local recording source for development and demos.

Pure-stdlib threaded HTTP server that mimics the field recording store:

* strong ETag per recording version, ``If-Match`` enforced (412 on mismatch)
* HTTP Range serving (206) without reading the whole file into memory
* per-recording injected latency and mid-stream connection cuts
* runtime version switching (v1 -> v2 -> ...) so ETag-based failure is demoable
* request/byte counters to prove that coalesced requests hit the source once

No PII: served files are synthetic tones generated by samples/generate.py.
"""
from __future__ import annotations

import json
import os
import re
import threading
import time
from http import HTTPStatus
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

SAMPLES_DIR = os.environ.get("SAMPLES_DIR", "/samples")
LISTEN_PORT = int(os.environ.get("PORT", "8080"))
DEFAULT_DELAY = float(os.environ.get("DEFAULT_DELAY", "0"))
DEFAULT_CUT = int(os.environ.get("DEFAULT_CUT_AFTER_BYTES", "0"))  # 0 = off

_ID_RE = re.compile(r"^[A-Za-z0-9._-]{1,128}$")


class Store:
    def __init__(self) -> None:
        self._lock = threading.RLock()
        self.versions: dict[str, list[str]] = {}
        self.active: dict[str, str] = {}
        self.behavior: dict[str, dict] = {}
        # Monotonic per-recording token bumped on every version switch. A
        # connection that started on an older token is stale and gets cut on
        # its next chunk, emulating an ETag becoming invalid mid-stream.
        self.generation: dict[str, int] = {}
        self.stats = {"requests": 0, "range_requests": 0, "bytes_served": 0, "cuts": 0}
        self._scan()

    def _scan(self) -> None:
        if not os.path.isdir(SAMPLES_DIR):
            return
        for rec_id in sorted(os.listdir(SAMPLES_DIR)):
            rec_dir = os.path.join(SAMPLES_DIR, rec_id)
            if not os.path.isdir(rec_dir) or not _ID_RE.match(rec_id):
                continue
            versions = sorted(
                name[:-4]
                for name in os.listdir(rec_dir)
                if name.startswith("v") and name.endswith(".wav")
            )
            if not versions:
                continue
            self.versions[rec_id] = versions
            self.active[rec_id] = versions[0]

    def etag(self, rec_id: str) -> str | None:
        with self._lock:
            version = self.active.get(rec_id)
            return f'"{rec_id}:{version}"' if version else None

    def path_for_active(self, rec_id: str) -> str | None:
        with self._lock:
            version = self.active.get(rec_id)
            if version is None:
                return None
            return os.path.join(SAMPLES_DIR, rec_id, f"{version}.wav")

    def set_version(self, rec_id: str, version: str) -> bool:
        with self._lock:
            if version not in self.versions.get(rec_id, []):
                return False
            if self.active.get(rec_id) != version:
                self.generation[rec_id] = self.generation.get(rec_id, 0) + 1
            self.active[rec_id] = version
            return True

    def current_generation(self, rec_id: str) -> int:
        with self._lock:
            return self.generation.get(rec_id, 0)

    def set_behavior(self, rec_id: str, delay: float, cut_after_bytes: int,
                     chunk_delay: float = 0.0) -> None:
        with self._lock:
            self.behavior[rec_id] = {
                "delay_seconds": max(0.0, float(delay)),
                "cut_after_bytes": max(0, int(cut_after_bytes)),
                "chunk_delay_seconds": max(0.0, float(chunk_delay)),
            }

    def get_behavior(self, rec_id: str) -> dict:
        with self._lock:
            cfg = self.behavior.get(
                rec_id,
                {
                    "delay_seconds": DEFAULT_DELAY,
                    "cut_after_bytes": DEFAULT_CUT,
                    "chunk_delay_seconds": 0.0,
                },
            )
            return dict(cfg)

    def reset(self) -> None:
        with self._lock:
            for rec_id, versions in self.versions.items():
                self.active[rec_id] = versions[0]
            self.behavior.clear()
            self.generation.clear()
            self.stats = {
                "requests": 0,
                "range_requests": 0,
                "bytes_served": 0,
                "cuts": 0,
            }

    def bump(self, **fields: int) -> None:
        with self._lock:
            for key, value in fields.items():
                self.stats[key] = self.stats.get(key, 0) + value

    def listing(self) -> dict:
        with self._lock:
            return {
                rec_id: {
                    "active_version": self.active[rec_id],
                    "etag": f'"{rec_id}:{self.active[rec_id]}"',
                    "versions": self.versions[rec_id],
                    "behavior": self.get_behavior(rec_id),
                }
                for rec_id in sorted(self.versions)
            }


STORE = Store()


class Handler(BaseHTTPRequestHandler):
    server_version = "BirdcallSource/1.0"
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt: str, *args) -> None:
        print(f"[source] {self.address_string()} {fmt % args}", flush=True)

    # ---------- helpers ----------
    def _json(self, status: int, payload: dict | list) -> None:
        body = json.dumps(payload).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _parse_range(self, header: str, size: int) -> tuple[int, int] | None:
        match = re.match(r"^bytes=(\d*)-(\d*)$", header.strip())
        if not match:
            return None
        start_s, end_s = match.groups()
        if start_s == "":  # suffix range bytes=-N
            length = int(end_s)
            if length <= 0:
                return None
            start, end = max(0, size - length), size - 1
        else:
            start = int(start_s)
            end = int(end_s) if end_s else size - 1
        if start >= size or end < start:
            return None
        return start, min(end, size - 1)

    # ---------- routing ----------
    def do_GET(self) -> None:
        path = self.path.split("?", 1)[0]
        if path == "/health":
            self._json(HTTPStatus.OK, {"status": "ok"})
        elif path == "/recordings":
            self._json(HTTPStatus.OK, STORE.listing())
        elif path == "/stats":
            with STORE._lock:
                self._json(HTTPStatus.OK, dict(STORE.stats))
        elif match := re.fullmatch(r"/recordings/([A-Za-z0-9._-]+)", path):
            self._serve_recording(match.group(1))
        elif match := re.fullmatch(r"/control/recordings/([A-Za-z0-9._-]+)", path):
            rec_id = match.group(1)
            if rec_id not in STORE.versions:
                self._json(HTTPStatus.NOT_FOUND, {"detail": "unknown recording"})
                return
            self._json(
                HTTPStatus.OK,
                {
                    "recording_id": rec_id,
                    "active_version": STORE.active[rec_id],
                    "etag": STORE.etag(rec_id),
                    "versions": STORE.versions[rec_id],
                    "behavior": STORE.get_behavior(rec_id),
                },
            )
        else:
            self._json(HTTPStatus.NOT_FOUND, {"detail": "no such route"})

    def do_POST(self) -> None:
        path = self.path.split("?", 1)[0]
        length = int(self.headers.get("Content-Length", "0") or 0)
        try:
            payload = json.loads(self.rfile.read(length) or b"{}")
        except json.JSONDecodeError:
            self._json(HTTPStatus.BAD_REQUEST, {"detail": "invalid JSON"})
            return

        if path == "/control/reset":
            STORE.reset()
            self._json(HTTPStatus.OK, {"reset": True, "recordings": STORE.listing()})
            return
        if path == "/control/stats/reset":
            with STORE._lock:
                STORE.stats = {
                    "requests": 0,
                    "range_requests": 0,
                    "bytes_served": 0,
                    "cuts": 0,
                }
            self._json(HTTPStatus.OK, {"reset": True})
            return

        match = re.fullmatch(r"/control/recordings/([A-Za-z0-9._-]+)/(version|behavior)", path)
        if not match:
            self._json(HTTPStatus.NOT_FOUND, {"detail": "no such route"})
            return
        rec_id, action = match.group(1), match.group(2)
        if rec_id not in STORE.versions:
            self._json(HTTPStatus.NOT_FOUND, {"detail": "unknown recording"})
            return

        if action == "version":
            version = str(payload.get("version", ""))
            if not STORE.set_version(rec_id, version):
                self._json(
                    HTTPStatus.BAD_REQUEST,
                    {"detail": f"unknown version {version!r}",
                     "available": STORE.versions[rec_id]},
                )
                return
            self._json(
                HTTPStatus.OK,
                {"recording_id": rec_id, "active_version": version,
                 "etag": STORE.etag(rec_id)},
            )
        else:
            STORE.set_behavior(
                rec_id,
                delay=payload.get("delay_seconds", 0.0),
                cut_after_bytes=payload.get("cut_after_bytes", 0),
                chunk_delay=payload.get("chunk_delay_seconds", 0.0),
            )
            self._json(HTTPStatus.OK, {
                "recording_id": rec_id,
                "behavior": STORE.get_behavior(rec_id),
            })

    # ---------- recording bytes ----------
    def _serve_recording(self, rec_id: str) -> None:
        file_path = STORE.path_for_active(rec_id)
        etag = STORE.etag(rec_id)
        if file_path is None:
            self._json(HTTPStatus.NOT_FOUND, {"detail": "unknown recording"})
            return

        if_match = self.headers.get("If-Match")
        if if_match is not None and if_match != etag:
            self.send_response(HTTPStatus.PRECONDITION_FAILED)
            self.send_header("ETag", etag or "")
            self.send_header("Content-Length", "0")
            self.end_headers()
            return

        try:
            size = os.path.getsize(file_path)
        except OSError:
            self._json(HTTPStatus.NOT_FOUND, {"detail": "recording file missing"})
            return

        range_header = self.headers.get("Range")
        start, end = 0, size - 1
        partial = False
        if range_header:
            parsed = self._parse_range(range_header, size)
            if parsed is None:
                self.send_response(HTTPStatus.REQUESTED_RANGE_NOT_SATISFIABLE)
                self.send_header("Content-Range", f"bytes */{size}")
                self.send_header("Content-Length", "0")
                self.end_headers()
                return
            start, end = parsed
            partial = True

        behavior = STORE.get_behavior(rec_id)
        if behavior["delay_seconds"]:
            time.sleep(behavior["delay_seconds"])
        generation_at_start = STORE.current_generation(rec_id)

        STORE.bump(requests=1, range_requests=1 if partial else 0)
        self.send_response(HTTPStatus.PARTIAL_CONTENT if partial else HTTPStatus.OK)
        self.send_header("ETag", etag or "")
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Type", "audio/wav")
        if partial:
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        self.send_header("Content-Length", str(end - start + 1))
        self.end_headers()

        cut = behavior["cut_after_bytes"]
        chunk_delay = behavior["chunk_delay_seconds"]
        written = 0
        # Only sizable (audio body) transfers are throttled; small header
        # range reads stay immediate so response headers arrive promptly.
        apply_chunk_delay = chunk_delay and (end - start + 1) > 64 * 1024
        try:
            with open(file_path, "rb") as fh:
                fh.seek(start)
                remaining = end - start + 1
                while remaining > 0:
                    # Small chunks when a per-chunk delay is configured so a
                    # slow stream can be observed/cancelled promptly.
                    block = min(8 * 1024 if apply_chunk_delay else 64 * 1024, remaining)
                    chunk = fh.read(block)
                    if not chunk:
                        break
                    if apply_chunk_delay:
                        time.sleep(chunk_delay)
                    # A version switch invalidates this connection: cut it so
                    # the extractor's fixed ETag read fails instead of serving
                    # bytes from a superseded recording.
                    if STORE.current_generation(rec_id) != generation_at_start:
                        STORE.bump(bytes_served=written, cuts=1)
                        self.log_message(
                            "version changed mid-stream; cutting stale connection for %s",
                            rec_id,
                        )
                        self.close_connection = True
                        return
                    if cut and written + len(chunk) >= cut:
                        chunk = chunk[: max(0, cut - written)]
                        self.wfile.write(chunk)
                        written += len(chunk)
                        STORE.bump(bytes_served=written, cuts=1)
                        self.log_message(
                            "simulated mid-stream cut after %d bytes for %s",
                            written, rec_id,
                        )
                        self.close_connection = True
                        return
                    self.wfile.write(chunk)
                    written += len(chunk)
                    remaining -= len(chunk)
            STORE.bump(bytes_served=written)
        except (BrokenPipeError, ConnectionResetError):
            # Client (the extractor) went away; record what was sent.
            STORE.bump(bytes_served=written)
            self.close_connection = True


def main() -> None:
    server = ThreadingHTTPServer(("0.0.0.0", LISTEN_PORT), Handler)
    print(f"[source] listening on :{LISTEN_PORT}, samples at {SAMPLES_DIR}", flush=True)
    print(f"[source] recordings: {sorted(STORE.versions)}", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
